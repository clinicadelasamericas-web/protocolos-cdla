-- =====================================================================
-- Biblioteca de protocolos CDLA para Oracle APEX 22.1
-- Equivalente a assets/protocolos.js + carpeta pdf/ + carpeta protocolos/
-- =====================================================================

create table cdla_protocolos (
  id              number generated by default on null as identity primary key,
  titulo          varchar2(200)  not null,
  tipo            varchar2(50)   not null,          -- Pathway, Protocolo, Guía...
  area            varchar2(100)  not null,          -- Emergencia, UTI...
  version         varchar2(20),
  descripcion     varchar2(1000),
  contenido_html  clob,                             -- cuerpo del <main class="documento">
  pdf_blob        blob,
  pdf_nombre      varchar2(255),
  pdf_mimetype    varchar2(100),
  pdf_actualizado date,
  activo          varchar2(1) default 'S' not null check (activo in ('S','N')),
  creado_por      varchar2(100) default coalesce(sys_context('APEX$SESSION','APP_USER'), user),
  creado_en       date default sysdate
);

create index cdla_protocolos_area_ix on cdla_protocolos (area, tipo);

